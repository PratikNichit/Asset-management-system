import { useState, useEffect } from 'react';
import Box from '@mui/material/Box';
import Typography from '@mui/material/Typography';
import Paper from '@mui/material/Paper';
import TextField from '@mui/material/TextField';
import MenuItem from '@mui/material/MenuItem';
import Snackbar from '@mui/material/Snackbar';
import Alert from '@mui/material/Alert';
import ArrowBackIcon from '@mui/icons-material/ArrowBack';
import PersonAddAlt1OutlinedIcon from '@mui/icons-material/PersonAddAlt1Outlined';
import SendOutlinedIcon from '@mui/icons-material/SendOutlined';

import { useAppDispatch, useAppSelector } from '../app/hooks';
import { addEmployee, selectAllEmployeesList } from '../redux/employeesSlice';
import { useLayout } from '../hooks/useLayout';
import AppButton from '../components/AppButton';
import type { Employee } from '../types/employee';

export interface AddEmployeePageProps {
  organizationName?: string;
  onCancel?: () => void;
  onSuccess?: () => void;
}

const DEPARTMENTS = [
  'Engineering',
  'Design',
  'Operations',
  'Production',
  'Quality',
  'Maintenance',
  'Finance',
  'Admin',
];

const LOCATIONS = [
  'HQ — Bengaluru',
  'Plant 1 — Pune',
  'Warehouse A',
  'Branch Office — Mumbai',
];

const EMPLOYMENT_TYPES = ['Full-time', 'Part-time', 'Contractor', 'Intern'];

const ACCESS_ROLES = ['Member', 'Admin', 'Viewer', 'Manager'];

export default function AddEmployeePage({
  organizationName = 'Atlas',
  onCancel,
  onSuccess,
}: AddEmployeePageProps) {
  const { setBreadcrumbs } = useLayout();
  const dispatch = useAppDispatch();
  const employees = useAppSelector(selectAllEmployeesList);

  // Auto-generated ID display
  const nextNum = employees.length + 1;
  const autoGeneratedId = `EMP-${String(nextNum).padStart(4, '0')}`;

  // Form State
  const [fullName, setFullName] = useState('');
  const [workEmail, setWorkEmail] = useState('');
  const [phone, setPhone] = useState('');
  const [jobTitle, setJobTitle] = useState('');
  const [department, setDepartment] = useState('');
  const [location, setLocation] = useState('');
  const [employmentType, setEmploymentType] = useState('Full-time');
  const [startDate, setStartDate] = useState('');
  const [accessRole, setAccessRole] = useState('Member');
  const [notes, setNotes] = useState('');

  // UI state
  const [toastMessage, setToastMessage] = useState<string | null>(null);

  useEffect(() => {
    setBreadcrumbs([organizationName, 'Employees', 'Add Employee']);
  }, [organizationName, setBreadcrumbs]);

  const handleSubmit = (e?: React.FormEvent) => {
    if (e) e.preventDefault();
    if (!fullName.trim() || !workEmail.trim() || !jobTitle.trim()) {
      setToastMessage('Please fill in all required fields (Full name, Work email, Job title).');
      return;
    }

    const newEmployee: Omit<Employee, 'id'> = {
      name: fullName.trim(),
      role: jobTitle.trim(),
      email: workEmail.trim(),
      department: department || 'Engineering',
      location: location || 'HQ — Bengaluru',
      joinedDate: startDate || new Date().toISOString().slice(0, 10),
      phone: phone.trim() || undefined,
      employmentType,
      accessRole,
      notes: notes.trim() || undefined,
    };

    dispatch(addEmployee(newEmployee));
    setToastMessage(`Successfully added employee ${fullName.trim()}`);
    if (onSuccess) {
      onSuccess();
    } else if (onCancel) {
      onCancel();
    }
  };

  const handleSendInvite = () => {
    if (!workEmail) {
      setToastMessage('Please enter a work email address first to send an invite.');
      return;
    }
    setToastMessage(`Workspace invite email sent to ${workEmail}`);
  };

  return (
    <Box sx={{ display: 'flex', flexDirection: 'column', gap: 3.5 }}>
      {/* ── Top Header Navigation Bar ───────────────────────────────────────── */}
      <Box
        sx={{
          display: 'flex',
          alignItems: 'center',
          justifyContent: 'space-between',
          flexWrap: 'wrap',
          gap: 2,
        }}
      >
        <Box>
          <Typography
            variant="h4"
            sx={{ fontWeight: 800, fontFamily: '"Manrope", sans-serif', fontSize: '1.75rem' }}
          >
            Add employee
          </Typography>
          <Typography variant="body2" color="text.secondary" sx={{ mt: 0.5, fontSize: '0.9rem' }}>
            Create a person record so assets can be assigned to them.
          </Typography>
        </Box>

        <Box sx={{ display: 'flex', alignItems: 'center', gap: 1.5 }}>
          {onCancel && (
            <AppButton
              variant="outline"
              size="sm"
              startIcon={<ArrowBackIcon />}
              onClick={onCancel}
              sx={{ borderColor: 'customColors.borderLight', color: 'text.primary', bgcolor: 'background.paper' }}
            >
              Cancel
            </AppButton>
          )}
          <AppButton
            variant="default"
            size="sm"
            startIcon={<PersonAddAlt1OutlinedIcon />}
            onClick={() => handleSubmit()}
          >
            Add employee
          </AppButton>
        </Box>
      </Box>

      {/* ── Main Form Content (2 Columns Layout) ─────────────────────────────── */}
      <Box
        component="form"
        onSubmit={handleSubmit}
        sx={{
          display: 'flex',
          gap: 3,
          alignItems: 'flex-start',
          flexWrap: { xs: 'wrap', lg: 'nowrap' },
        }}
      >
        {/* ── Left Main Column (Sections 1, 2, 3) ───────────────────────────── */}
        <Box
          sx={{
            flex: 1,
            minWidth: 0,
            display: 'flex',
            flexDirection: 'column',
            gap: 3,
            width: '100%',
          }}
        >
          {/* Section 1: Personal Details */}
          <Paper
            variant="outlined"
            sx={{
              p: 3,
              borderRadius: 2.5,
              borderColor: 'customColors.borderLight',
              bgcolor: 'background.paper',
            }}
          >
            <Box sx={{ mb: 2.5 }}>
              <Typography
                variant="h6"
                sx={{ fontWeight: 700, fontSize: '1.05rem', fontFamily: '"Manrope", sans-serif' }}
              >
                Personal details
              </Typography>
              <Typography variant="body2" color="text.secondary" sx={{ fontSize: '0.83rem', mt: 0.25 }}>
                Basic identity and contact information.
              </Typography>
            </Box>

            <Box
              sx={{
                display: 'grid',
                gridTemplateColumns: { xs: '1fr', sm: '1fr 1fr' },
                gap: 2.5,
              }}
            >
              {/* Full Name */}
              <Box>
                <Typography sx={{ fontSize: '0.82rem', fontWeight: 600, mb: 0.75 }}>
                  Full name <span style={{ color: '#E62C2C' }}>*</span>
                </Typography>
                <TextField
                  fullWidth
                  size="small"
                  placeholder="e.g. Priya Sharma"
                  value={fullName}
                  onChange={(e) => setFullName(e.target.value)}
                  sx={{
                    '& fieldset': { borderColor: 'customColors.borderLight' },
                    '&:hover fieldset': { borderColor: 'primary.main' },
                    '& .MuiOutlinedInput-root': { borderRadius: 1.5, fontSize: '0.88rem' },
                  }}
                />
              </Box>

              {/* Employee ID */}
              <Box>
                <Box sx={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', mb: 0.75 }}>
                  <Typography sx={{ fontSize: '0.82rem', fontWeight: 600 }}>Employee ID</Typography>
                  <Typography sx={{ fontSize: '0.75rem', color: 'text.secondary' }}>- Auto-generated</Typography>
                </Box>
                <TextField
                  fullWidth
                  disabled
                  size="small"
                  value={autoGeneratedId}
                  sx={{
                    '& fieldset': { borderColor: 'customColors.borderLight' },
                    '& .MuiOutlinedInput-root': { borderRadius: 1.5, fontSize: '0.88rem', bgcolor: 'customColors.bgLight' },
                  }}
                />
              </Box>

              {/* Work Email */}
              <Box>
                <Typography sx={{ fontSize: '0.82rem', fontWeight: 600, mb: 0.75 }}>
                  Work email <span style={{ color: '#E62C2C' }}>*</span>
                </Typography>
                <TextField
                  fullWidth
                  type="email"
                  size="small"
                  placeholder="name@company.com"
                  value={workEmail}
                  onChange={(e) => setWorkEmail(e.target.value)}
                  sx={{
                    '& fieldset': { borderColor: 'customColors.borderLight' },
                    '&:hover fieldset': { borderColor: 'primary.main' },
                    '& .MuiOutlinedInput-root': { borderRadius: 1.5, fontSize: '0.88rem' },
                  }}
                />
              </Box>

              {/* Phone */}
              <Box>
                <Typography sx={{ fontSize: '0.82rem', fontWeight: 600, mb: 0.75 }}>Phone</Typography>
                <TextField
                  fullWidth
                  size="small"
                  placeholder="+1 555 0100"
                  value={phone}
                  onChange={(e) => setPhone(e.target.value)}
                  sx={{
                    '& fieldset': { borderColor: 'customColors.borderLight' },
                    '&:hover fieldset': { borderColor: 'primary.main' },
                    '& .MuiOutlinedInput-root': { borderRadius: 1.5, fontSize: '0.88rem' },
                  }}
                />
              </Box>
            </Box>
          </Paper>

          {/* Section 2: Role & Placement */}
          <Paper
            variant="outlined"
            sx={{
              p: 3,
              borderRadius: 2.5,
              borderColor: 'customColors.borderLight',
              bgcolor: 'background.paper',
            }}
          >
            <Box sx={{ mb: 2.5 }}>
              <Typography
                variant="h6"
                sx={{ fontWeight: 700, fontSize: '1.05rem', fontFamily: '"Manrope", sans-serif' }}
              >
                Role &amp; placement
              </Typography>
              <Typography variant="body2" color="text.secondary" sx={{ fontSize: '0.83rem', mt: 0.25 }}>
                Where this person sits in the organization.
              </Typography>
            </Box>

            <Box
              sx={{
                display: 'grid',
                gridTemplateColumns: { xs: '1fr', sm: '1fr 1fr' },
                gap: 2.5,
              }}
            >
              {/* Job Title */}
              <Box>
                <Typography sx={{ fontSize: '0.82rem', fontWeight: 600, mb: 0.75 }}>
                  Job title <span style={{ color: '#E62C2C' }}>*</span>
                </Typography>
                <TextField
                  fullWidth
                  size="small"
                  placeholder="e.g. Maintenance Technician"
                  value={jobTitle}
                  onChange={(e) => setJobTitle(e.target.value)}
                  sx={{
                    '& fieldset': { borderColor: 'customColors.borderLight' },
                    '&:hover fieldset': { borderColor: 'primary.main' },
                    '& .MuiOutlinedInput-root': { borderRadius: 1.5, fontSize: '0.88rem' },
                  }}
                />
              </Box>

              {/* Department */}
              <Box>
                <Typography sx={{ fontSize: '0.82rem', fontWeight: 600, mb: 0.75 }}>Department</Typography>
                <TextField
                  select
                  fullWidth
                  size="small"
                  value={department}
                  onChange={(e) => setDepartment(e.target.value)}
                  slotProps={{ select: { displayEmpty: true } }}
                  sx={{
                    '& fieldset': { borderColor: 'customColors.borderLight' },
                    '&:hover fieldset': { borderColor: 'primary.main' },
                    '& .MuiOutlinedInput-root': { borderRadius: 1.5, fontSize: '0.88rem' },
                  }}
                >
                  <MenuItem value="" disabled sx={{ color: 'text.disabled', fontSize: '0.88rem' }}>
                    Select department
                  </MenuItem>
                  {DEPARTMENTS.map((dept) => (
                    <MenuItem key={dept} value={dept} sx={{ fontSize: '0.88rem' }}>
                      {dept}
                    </MenuItem>
                  ))}
                </TextField>
              </Box>

              {/* Location */}
              <Box>
                <Typography sx={{ fontSize: '0.82rem', fontWeight: 600, mb: 0.75 }}>Location</Typography>
                <TextField
                  select
                  fullWidth
                  size="small"
                  value={location}
                  onChange={(e) => setLocation(e.target.value)}
                  slotProps={{ select: { displayEmpty: true } }}
                  sx={{
                    '& fieldset': { borderColor: 'customColors.borderLight' },
                    '&:hover fieldset': { borderColor: 'primary.main' },
                    '& .MuiOutlinedInput-root': { borderRadius: 1.5, fontSize: '0.88rem' },
                  }}
                >
                  <MenuItem value="" disabled sx={{ color: 'text.disabled', fontSize: '0.88rem' }}>
                    Select location
                  </MenuItem>
                  {LOCATIONS.map((loc) => (
                    <MenuItem key={loc} value={loc} sx={{ fontSize: '0.88rem' }}>
                      {loc}
                    </MenuItem>
                  ))}
                </TextField>
              </Box>

              {/* Employment Type */}
              <Box>
                <Typography sx={{ fontSize: '0.82rem', fontWeight: 600, mb: 0.75 }}>Employment type</Typography>
                <TextField
                  select
                  fullWidth
                  size="small"
                  value={employmentType}
                  onChange={(e) => setEmploymentType(e.target.value)}
                  sx={{
                    '& fieldset': { borderColor: 'customColors.borderLight' },
                    '&:hover fieldset': { borderColor: 'primary.main' },
                    '& .MuiOutlinedInput-root': { borderRadius: 1.5, fontSize: '0.88rem' },
                  }}
                >
                  {EMPLOYMENT_TYPES.map((type) => (
                    <MenuItem key={type} value={type} sx={{ fontSize: '0.88rem' }}>
                      {type}
                    </MenuItem>
                  ))}
                </TextField>
              </Box>

              {/* Start Date */}
              <Box>
                <Typography sx={{ fontSize: '0.82rem', fontWeight: 600, mb: 0.75 }}>Start date</Typography>
                <TextField
                  type="date"
                  fullWidth
                  size="small"
                  value={startDate}
                  onChange={(e) => setStartDate(e.target.value)}
                  placeholder="mm/dd/yyyy"
                  slotProps={{ inputLabel: { shrink: true } }}
                  sx={{
                    '& fieldset': { borderColor: 'customColors.borderLight' },
                    '&:hover fieldset': { borderColor: 'primary.main' },
                    '& .MuiOutlinedInput-root': { borderRadius: 1.5, fontSize: '0.88rem' },
                  }}
                />
              </Box>

              {/* Access Role */}
              <Box>
                <Typography sx={{ fontSize: '0.82rem', fontWeight: 600, mb: 0.75 }}>Access role</Typography>
                <TextField
                  select
                  fullWidth
                  size="small"
                  value={accessRole}
                  onChange={(e) => setAccessRole(e.target.value)}
                  sx={{
                    '& fieldset': { borderColor: 'customColors.borderLight' },
                    '&:hover fieldset': { borderColor: 'primary.main' },
                    '& .MuiOutlinedInput-root': { borderRadius: 1.5, fontSize: '0.88rem' },
                  }}
                >
                  {ACCESS_ROLES.map((role) => (
                    <MenuItem key={role} value={role} sx={{ fontSize: '0.88rem' }}>
                      {role}
                    </MenuItem>
                  ))}
                </TextField>
              </Box>
            </Box>
          </Paper>

          {/* Section 3: Notes */}
          <Paper
            variant="outlined"
            sx={{
              p: 3,
              borderRadius: 2.5,
              borderColor: 'customColors.borderLight',
              bgcolor: 'background.paper',
            }}
          >
            <Typography
              variant="h6"
              sx={{ fontWeight: 700, fontSize: '1.05rem', fontFamily: '"Manrope", sans-serif', mb: 2 }}
            >
              Notes
            </Typography>

            <TextField
              multiline
              rows={3}
              fullWidth
              placeholder="Shift pattern, certifications, notes..."
              value={notes}
              onChange={(e) => setNotes(e.target.value)}
              sx={{
                '& fieldset': { borderColor: 'customColors.borderLight' },
                '&:hover fieldset': { borderColor: 'primary.main' },
                '& .MuiOutlinedInput-root': { borderRadius: 1.5, fontSize: '0.88rem' },
              }}
            />
          </Paper>
        </Box>

        {/* ── Right Sidebar Column (Invite & Tip Cards) ──────────────────────── */}
        <Box
          sx={{
            width: { xs: '100%', lg: 320, xl: 350 },
            flexShrink: 0,
            display: 'flex',
            flexDirection: 'column',
            gap: 2.5,
          }}
        >
          {/* Card 1: Invite */}
          <Paper
            variant="outlined"
            sx={{
              p: 3,
              borderRadius: 2.5,
              borderColor: 'customColors.borderLight',
              bgcolor: 'background.paper',
            }}
          >
            <Typography
              variant="h6"
              sx={{ fontWeight: 700, fontSize: '0.98rem', fontFamily: '"Manrope", sans-serif', mb: 0.5 }}
            >
              Invite
            </Typography>
            <Typography variant="body2" color="text.secondary" sx={{ fontSize: '0.82rem', mb: 2.5, lineHeight: 1.4 }}>
              Send a workspace invitation so this person can view assets assigned to them.
            </Typography>

            <AppButton
              variant="outline"
              size="sm"
              fullWidth
              startIcon={<SendOutlinedIcon sx={{ fontSize: 16 }} />}
              onClick={handleSendInvite}
              sx={{ borderColor: 'customColors.borderLight', color: 'text.primary', py: 1 }}
            >
              Send Invite email
            </AppButton>
          </Paper>

          {/* Card 2: Tip Box */}
          <Paper
            variant="outlined"
            sx={{
              p: 2.5,
              borderRadius: 2.5,
              borderColor: 'customColors.borderLight',
              bgcolor: 'customColors.bgLight',
            }}
          >
            <Typography variant="body2" color="text.secondary" sx={{ fontSize: '0.82rem', lineHeight: 1.5 }}>
              <strong>Tip:</strong> Import many people at once from the Employees page using{' '}
              <strong style={{ color: '#1B1B1B' }}>Import CSV</strong>.
            </Typography>
          </Paper>
        </Box>
      </Box>

      {/* Snackbar notification */}
      <Snackbar
        open={Boolean(toastMessage)}
        autoHideDuration={4000}
        onClose={() => setToastMessage(null)}
        anchorOrigin={{ vertical: 'bottom', horizontal: 'right' }}
      >
        <Alert onClose={() => setToastMessage(null)} severity="info" sx={{ width: '100%' }}>
          {toastMessage}
        </Alert>
      </Snackbar>
    </Box>
  );
}
